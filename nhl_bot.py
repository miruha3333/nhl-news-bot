def escape_html(text):
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def is_duplicate(new_text, existing_texts, threshold=0.8):
    for text in existing_texts:
        similarity = difflib.SequenceMatcher(
            None,
            new_text,
            text,
        ).ratio()

        if similarity > threshold:
            return True

    return False


def clean_raw_rss_text(raw_text):
    if not raw_text:
        return ""

    text = re.sub(r"<[^>]+>", "", raw_text)
    text = re.sub(
        r"view original|generated by rss\.app",
        "",
        text,
        flags=re.IGNORECASE,
    )

    return text.strip()


def clean_bot_hallucinations(text):
    if not text:
        return text

    chat_triggers = [
        "я понял задачу",
        "понял задачу",
        "давайте ваш текст",
        "вот ваш перевод",
        "конечно, вот",
        "адаптированный пост",
    ]

    if any(trigger in text.lower() for trigger in chat_triggers):
        print(
            "⚠️ Обнаружен пустой диалог нейросети вместо новости. "
            "Блокируем."
        )
        return ""

    replacements = {
        "гендир": "генеральный менеджер",
        "дженерал менеджер": "генеральный менеджер",
        "сработать сделка": "провернуть сделку",
    }

    for bad_word, good_word in replacements.items():
        text = re.sub(
            r"\b" + re.escape(bad_word) + r"\b",
            good_word,
            text,
            flags=re.IGNORECASE,
        )

    return text


def get_entry_id(entry):
    return (
        getattr(entry, "id", None)
        or getattr(entry, "guid", None)
        or getattr(entry, "link", None)
        or clean_raw_rss_text(getattr(entry, "title", ""))
    )


def download_image(query):
    clean_query = (
        f"{query} "
        "-getty -alamy -shutterstock -stock "
        "-watermark -ai -generated -midjourney "
        "-dalle -art -render -drawing -illustration"
    )

    headers = {
        "User-Agent": (
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
            "AppleWebKit/537.36 "
            "(KHTML, like Gecko) "
            "Chrome/122.0.0.0 Safari/537.36"
        )
    }

    bad_url_words = [
        "alamy",
        "getty",
        "shutterstock",
        "depositphotos",
        "stock",
        "dreamstime",
        "vector",
        "illustration",
    ]

    try:
        print(f"🖼️ Поиск изображения: {query}")

        with DDGS() as ddgs:
            results = list(
                ddgs.images(
                    query=clean_query,
                    max_results=30,
                    layout="Wide",
                    size="Large",
                )
            )

            print(f"Получено результатов изображений: {len(results)}")

            for res in results:
                img_url = res.get("image")

                if not img_url:
                    continue

                if image_exists(img_url):
                    print("⚠️ Изображение уже использовалось. Пропускаем.")
                    continue

                if any(
                    bad_word in img_url.lower()
                    for bad_word in bad_url_words
                ):
                    continue

                try:
                    response = requests.get(
                        img_url,
                        headers=headers,
                        timeout=10,
                    )

                    if response.status_code != 200:
                        continue

                    content_type = response.headers.get(
                        "Content-Type",
                        "",
                    ).lower()

                    if not content_type.startswith("image/"):
                        print(
                            f"⚠️ URL не является изображением: "
                            f"{content_type}"
                        )
                        continue

                    if len(response.content) < 5000:
                        print("⚠️ Изображение слишком маленькое. Пропускаем.")
                        continue

                    extension = ".jpg"

                    if "png" in content_type:
                        extension = ".png"
                    elif "webp" in content_type:
                        extension = ".webp"
                    elif "gif" in content_type:
                        extension = ".gif"

                    temp_file = tempfile.NamedTemporaryFile(
                        delete=False,
                        suffix=extension,
                    )

                    temp_file.write(response.content)
                    temp_file.close()

                    save_image(img_url)
                    mark_image_used(img_url)

                    print(f"✅ Изображение найдено: {img_url}")

                    return temp_file.name

                except Exception as e:
                    print(f"⚠️ Ошибка скачивания изображения: {e}")
                    continue

    except Exception as e:
        print(f"❌ Ошибка поиска картинок: {e}")

    return None


