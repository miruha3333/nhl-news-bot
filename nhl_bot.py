def escape_html(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def is_duplicate(new_text, existing_texts):
    for text in existing_texts:
        similarity = difflib.SequenceMatcher(None, new_text, text).ratio()
        if similarity > 0.8:
            return True
    return False


def clean_raw_rss_text(raw_text):
    if not raw_text:
        return ""
    text = re.sub(r"<[^>]+>", "", raw_text)
    text = re.sub(r"view original|generated by rss\.app", "", text, flags=re.IGNORECASE)
    return text.strip()


def clean_bot_hallucinations(text):
    if not text:
        return text

    chat_triggers = [
        "я понял задачу",
        "понял задачу",
        "давайте ваш текст",
        "вот ваш перевод",
        "конечно, вот",
        "адаптированный пост",
    ]
    if any(trigger in text.lower() for trigger in chat_triggers):
        print("⚠️ Обнаружен пустой диалог нейросети вместо новости. Блокируем.")
        return ""

    replacements = {
        "гендир": "генеральный менеджер",
        "дженерал менеджер": "генеральный менеджер",
        "сработать сделка": "провернуть сделку",
    }
    for bad_word, good_word in replacements.items():
        text = re.sub(
            r"\b" + re.escape(bad_word) + r"\b", good_word, text, flags=re.IGNORECASE
        )
    return text


def parse_final_post_text(ai_text):
    """Извлекает блок [FINAL_POST] и очищает его от лишних символов и тегов мыслей."""
    if not ai_text:
        return None

    # Отрезаем размышления DeepSeek-R1, если они присутствуют
    ai_text = re.sub(r"<think>.*?</think>", "", ai_text, flags=re.DOTALL)

    if "[FINAL_POST]" in ai_text and "[/FINAL_POST]" in ai_text:
        ai_text = ai_text.split("[FINAL_POST]")[1].split("[/FINAL_POST]")[0].strip()

    cleaned = (
        ai_text.replace("**", "")
        .replace('"', "")
        .replace("«", "")
        .replace("»", "")
        .strip()
    )
    return cleaned if len(cleaned) > 10 else None


