def download_image(query):
    clean_query = f"{query} -getty -alamy -shutterstock -stock -watermark -ai -generated -midjourney -dalle -art -render -drawing -illustration"
    time.sleep(2)

    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"
    }
    bad_url_words = [
        "alamy",
        "getty",
        "shutterstock",
        "depositphotos",
        "stock",
        "dreamstime",
        "vector",
        "illustration",
    ]
    image_history = get_image_history()

    try:
        with DDGS() as ddgs:
            results = list(
                ddgs.images(
                    query=clean_query, max_results=30, layout="Wide", size="Large"
                )
            )

            for res in results:
                img_url = res.get("image")
                if not img_url or img_url in image_history:
                    continue
                if any(bad in img_url.lower() for bad in bad_url_words):
                    continue

                try:
                    response = requests.get(img_url, headers=headers, timeout=10)
                    if response.status_code == 200:
                        add_to_image_history(img_url)
                        with open("temp.png", "wb") as handler:
                            handler.write(response.content)
                        return "temp.png"
                except Exception:
                    continue
    except Exception as e:
        print(f"Ошибка поиска картинок: {e}")
    return None


def alternate_posts(posts):
    if not posts:
        return []
    grouped = defaultdict(list)
    for p in posts:
        grouped[p["query"]].append(p)

    sorted_posts = []
    while any(grouped.values()):
        for key in list(grouped.keys()):
            if grouped[key]:
                sorted_posts.append(grouped[key].pop(0))
            else:
                del grouped[key]
    return sorted_posts


def main():
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36"
    }

    feed = None
    try:
        print(f"Загрузка RSS: {RSS_URL}...")
        response = requests.get(RSS_URL, headers=headers, timeout=15)
        if response.status_code == 200:
            parsed = feedparser.parse(response.content)
            if parsed.entries:
                feed = parsed
    except Exception as e:
        print(f"❌ Ошибка загрузки RSS: {e}")

    if not feed or not feed.entries:
        print("❌ Не удалось получить новости из RSS-потока.")
        return

    history = get_history()

    new_entries = []
    for entry in reversed(feed.entries[:10]):
        entry_id = getattr(entry, "id", None) or getattr(entry, "link", None)
        title = (
            getattr(entry, "title", "").strip()
            or getattr(entry, "summary", "").strip()
        )
        clean_title = clean_raw_rss_text(title)

        check_val = entry_id if entry_id else clean_title

        if clean_title and check_val not in history and clean_title not in history:
            entry.title = clean_title
            entry.history_id = check_val
            new_entries.append(entry)

    if not new_entries:
        print("Новых постов нет.")
        return

    raw_posts_pool = []
    entries_to_save = []

    for entry in new_entries:
        raw_response = translate_tweet(entry.title)
        if raw_response:
            query_part = "NHL match action"
            post_text = raw_response
            if "SEARCH_QUERY:" in raw_response:
                idx = raw_response.rfind("SEARCH_QUERY:")
                post_text = raw_response[:idx].strip()
                query_part = raw_response[idx:].replace("SEARCH_QUERY:", "").strip()

            post_text = clean_bot_hallucinations(post_text)

            if not post_text.strip():
                entries_to_save.append(entry.history_id)
                continue

            if ": " in post_text:
                author, text_content = post_text.split(": ", 1)
                raw_posts_pool.append(
                    {
                        "author": author.replace("Источник", "").strip(),
                        "text": text_content,
                        "query": query_part,
                        "entry_id": entry.history_id,
                    }
                )
            else:
                raw_posts_pool.append(
                    {
                        "author": "",
                        "text": post_text,
                        "query": query_part,
                        "entry_id": entry.history_id,
                    }
                )

    alternated_posts = alternate_posts(raw_posts_pool)

    combined_texts = []
    pure_texts_for_diff = []
    search_queries = []

    for p in alternated_posts:
        if is_duplicate(p["text"], pure_texts_for_diff):
            entries_to_save.append(p["entry_id"])
            continue

        pure_texts_for_diff.append(p["text"])
        if p["author"]:
            formatted_text = (
                f"<b>{escape_html(p['author'])}</b>\n{escape_html(p['text'])}"
            )
        else:
            formatted_text = escape_html(p["text"])

        combined_texts.append(formatted_text)
        search_queries.append(p["query"])
        entries_to_save.append(p["entry_id"])

    if combined_texts:
        final_post = "\n\n".join(combined_texts)
        image_path = None

        for query in search_queries:
            image_path = download_image(query)
            if image_path:
                break

        if not image_path:
            image_path = download_image("NHL ice hockey match action")

        try:
            image_sent = False
            if image_path and os.path.exists(image_path):
                try:
                    with open(image_path, "rb") as photo:
                        if len(final_post) <= 1024:
                            bot.send_photo(
                                CHANNEL_ID,
                                photo,
                                caption=final_post,
                                parse_mode="HTML",
                            )
                        else:
                            bot.send_photo(CHANNEL_ID, photo)
                            bot.send_message(CHANNEL_ID, final_post, parse_mode="HTML")
                    image_sent = True
                except Exception as e:
                    print(f"⚠️ Telegram отклонил файл: {e}")
                finally:
                    if os.path.exists(image_path):
                        os.remove(image_path)

            if not image_sent:
                bot.send_message(CHANNEL_ID, final_post, parse_mode="HTML")

            for item_id in entries_to_save:
                add_to_history(item_id)

        except Exception as e:
            print(f"❌ Ошибка отправки: {e}")


if __name__ == "__main__":
    main()
