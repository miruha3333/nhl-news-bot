def parse_ai_response(raw_response):
    if not raw_response:
        return None, None

    query_part = "NHL match action"
    post_text = raw_response.strip()

    if "SEARCH_QUERY:" in raw_response:
        idx = raw_response.rfind("SEARCH_QUERY:")

        post_text = raw_response[:idx].strip()

        query_part = (
            raw_response[idx:]
            .replace("SEARCH_QUERY:", "", 1)
            .strip()
        )

    post_text = clean_bot_hallucinations(post_text)

    if not post_text.strip():
        return None, None

    if "SEARCH_QUERY:" in query_part:
        query_part = (
            query_part
            .replace("SEARCH_QUERY:", "")
            .strip()
        )

    if not query_part:
        query_part = "NHL match action"

    return post_text.strip(), query_part.strip()


def send_telegram_with_retry(final_post, image_path=None):
    last_error = None

    for attempt in range(1, 4):
        try:
            print(
                f"📨 Отправка в Telegram. "
                f"Попытка {attempt}/3..."
            )

            if image_path and os.path.exists(image_path):
                with open(image_path, "rb") as photo:
                    message = bot.send_photo(
                        CHANNEL_ID,
                        photo,
                        caption=final_post,
                        parse_mode="HTML",
                    )

                return message

            message = bot.send_message(
                CHANNEL_ID,
                final_post,
                parse_mode="HTML",
            )

            return message

        except Exception as e:
            last_error = e

            print(
                f"⚠️ Ошибка Telegram "
                f"на попытке {attempt}/3: {e}"
            )

            if attempt < 3:
                time.sleep(5 * attempt)

    raise last_error


def process_entry(entry, already_processed_texts):
    entry_id = get_entry_id(entry)

    title = (
        getattr(entry, "title", "").strip()
        or getattr(entry, "summary", "").strip()
    )

    title = clean_raw_rss_text(title)

    entry_link = getattr(entry, "link", "")

    if not entry_id:
        print("⚠️ Пропускаем новость без ID.")
        return False

    if not title:
        print(f"⚠️ Пропускаем новость без заголовка: {entry_id}")
        return False

    if news_exists(entry_id):
        print(f"↩️ Новость уже есть в базе: {title}")
        return False

    print("")
    print("=" * 70)
    print(f"📰 Новость: {title}")
    print(f"🆔 ID: {entry_id}")
    print("=" * 70)

    save_news(
        source_id=entry_id,
        title=title,
        url=entry_link,
        status="processing",
    )

    raw_response = translate_tweet(
        title,
        entry_id,
    )

    if not raw_response:
        update_news_status(
            entry_id,
            "ai_failed",
        )

        print(
            "❌ Не удалось получить корректный текст "
            "от Gemini."
        )

        return False

    post_text, search_query = parse_ai_response(
        raw_response
    )

    if not post_text:
        update_news_status(
            entry_id,
            "ai_validation_failed",
        )

        save_error(
            entry_id,
            "AI_VALIDATION_ERROR",
            "Post text is empty after parsing",
        )

        print("❌ AI-ответ не прошёл проверку.")

        return False

    if is_duplicate(
        post_text,
        already_processed_texts,
        threshold=0.8,
    ):
        update_news_status(
            entry_id,
            "duplicate",
        )

        save_error(
            entry_id,
            "DUPLICATE",
            "Post is too similar to another post in current run",
        )

        print(
            "↩️ Похожий пост уже обрабатывался "
            "в текущем запуске. Пропускаем."
        )

        return False

    already_processed_texts.append(post_text)

    if ": " in post_text:
        author, text_content = post_text.split(
            ": ",
            1,
        )

        author = (
            author
            .replace("Источник", "")
            .strip()
        )

        if author:
            final_post = (
                f"<b>{escape_html(author)}</b>\n"
                f"{escape_html(text_content)}"
            )
        else:
            final_post = escape_html(text_content)

    else:
        final_post = escape_html(post_text)

    print(f"🔎 Поисковый запрос для изображения: {search_query}")

    image_path = download_image(search_query)

    if not image_path:
        print(
            "⚠️ По основному запросу изображение "
            "не найдено. Используем запасной запрос."
        )

        image_path = download_image(
            "NHL ice hockey match action"
        )

    try:
        telegram_message = send_telegram_with_retry(
            final_post,
            image_path,
        )

        update_news_status(
            entry_id,
            "published",
            published_at=__import__("datetime")
            .datetime.now(
                __import__("datetime").timezone.utc
            ).isoformat(),
            telegram_message_id=getattr(
                telegram_message,
                "message_id",
                None,
            ),
        )

        print(
            f"✅ Новость успешно опубликована в Telegram: "
            f"{title}"
        )

        return True

    except Exception as e:
        print(
            f"❌ Не удалось отправить новость в Telegram: "
            f"{e}"
        )

        update_news_status(
            entry_id,
            "telegram_failed",
        )

        save_error(
            entry_id,
            "TELEGRAM_ERROR",
            str(e),
        )

        return False

    finally:
        if image_path and os.path.exists(image_path):
            try:
                os.remove(image_path)
            except Exception as e:
                print(
                    f"⚠️ Не удалось удалить временное изображение: "
                    f"{e}"
                )


def main():
    init_db()

    if not TOKEN:
        print("❌ Не задана переменная TOKEN.")
        return

    if not GEMINI_API_KEY:
        print("❌ Не задана переменная GEMINI_API_KEY.")
        return

    headers = {
        "User-Agent": (
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
            "AppleWebKit/537.36 "
            "(KHTML, like Gecko) "
            "Chrome/122.0.0.0 Safari/537.36"
        )
    }

    feed = None

    try:
        print(f"Загрузка RSS: {RSS_URL}...")

        response = requests.get(
            RSS_URL,
            headers=headers,
            timeout=15,
        )

        if response.status_code == 200:
            parsed = feedparser.parse(
                response.content
            )

            if parsed.entries:
                feed = parsed

        else:
            error_message = (
                f"RSS вернул HTTP {response.status_code}"
            )

            print(f"❌ {error_message}")

            save_error(
                None,
                "RSS_ERROR",
                error_message,
            )

    except Exception as e:
        print(f"❌ Ошибка загрузки RSS: {e}")

        save_error(
            None,
            "RSS_ERROR",
            str(e),
        )

    if not feed or not feed.entries:
        print(
            "❌ Не удалось получить новости из RSS-потока."
        )
        return

    print(
        f"Получено записей RSS: {len(feed.entries)}"
    )

    new_entries = []

    for entry in reversed(feed.entries[:30]):
        entry_id = get_entry_id(entry)

        title = (
            getattr(entry, "title", "").strip()
            or getattr(entry, "summary", "").strip()
        )

        clean_title = clean_raw_rss_text(title)

        if not entry_id or not clean_title:
            continue

        if news_exists(entry_id):
            continue

        new_entries.append(entry)

    if not new_entries:
        print("Новых постов нет.")
        return

    print(
        f"Найдено новых новостей для обработки: "
        f"{len(new_entries)}"
    )

    already_processed_texts = []

    success_count = 0
    failed_count = 0

    for entry in new_entries:
        try:
            success = process_entry(
                entry,
                already_processed_texts,
            )

            if success:
                success_count += 1
            else:
                failed_count += 1

        except Exception as e:
            entry_id = get_entry_id(entry)

            print(
                f"❌ Критическая ошибка обработки "
                f"новости {entry_id}: {e}"
            )

            save_error(
                entry_id,
                "PROCESSING_ERROR",
                str(e),
            )

            update_news_status(
                entry_id,
                "processing_failed",
            )

            failed_count += 1

    print("")
    print("=" * 70)
    print("ИТОГ ЗАПУСКА")
    print(f"Успешно опубликовано: {success_count}")
    print(f"Ошибок/пропущено: {failed_count}")
    print("=" * 70)


if __name__ == "__main__":
    main()
